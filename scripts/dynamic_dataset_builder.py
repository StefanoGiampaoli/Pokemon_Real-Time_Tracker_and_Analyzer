def build_old_dataset(df, columns):
    for id, types in PRE_GEN_6_TYPE_CHANGES.items():
        mask = df.get(id, None) 
        if mask:
            mask[2] = types[0].lower() if types[0] else None
            mask[3] = types[1].lower() if types[1] else None

    for type in TYPE_CHART_GEN_2_TO_5:
        columns.append(f"against_{type}")

    for pkmn_info in df.values():
        type1 = pkmn_info[2] if pkmn_info[2] else None
        type2 = pkmn_info[3] if pkmn_info[3] else None

        for type in TYPE_CHART_GEN_2_TO_5:
            damage_on_type1 = TYPE_CHART_GEN_2_TO_5.get(type, {}).get(type1.capitalize(), 1)
            if type2:
                damage_on_type2 = TYPE_CHART_GEN_2_TO_5.get(type, {}).get(type2.capitalize(), 1)
            final_damage = damage_on_type1 * damage_on_type2 if type2 else damage_on_type1
            pkmn_info.append(final_damage)

    return df, columns

